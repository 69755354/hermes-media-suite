#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
分镜/提示词定案核验脚本（通用模板，2026-08-23 火龙 S01 实测）
用途：codex 重写分镜/提示词后，出稿交付前强制核验——缺任一条用户已定案规则即 BLOCK。
不靠人眼 diff，不靠自觉，用户不当质检员。
用法：
  python3 verify_storyboard_checks.py <分镜文件路径>
清单来源：旧版分镜（被重写的那一版）+ 用户逐条定案。每次重写后把定案关键词同步进 CHECKS。
"""
import sys

def load(path):
    with open(path, encoding="utf-8") as f:
        return f.read()

# 定案规则清单：每条 = (规则名, 必须出现的关键词列表, 说明)
# ⚠️ 2026-09-21 优矩新规：违禁利益点（无广告类/躺赚白嫖/吊打竞品/绝对免费/直接提现）不得再作为必须出现的校验项。
# 火龙 S01 示例（2026-08-23）：台词 9 句 73 字一字不改 / 硬切点 10.050 不动 /
# 「直接」两字锚定起身 / 手机全程举屏 / @图3 原样保留不重绘 + 透视形变圆角裁切 /
# 声音（年龄/音色/表达） / 口型同步 / 镜头后退跟随 / 负面只放画面风险 / 参考图路径。
# 新项目重写分镜时，把「旧版分镜里用户确认过的每一条」都列进这里。
CHECKS = [
    ("台词9句完整", ["喂你知道吗", "现在看漫剧也能赚零花钱了", "就是这个火龙漫剧",
                   "直接把福利拉满", "平时看剧过程中",
                   "看剧就能攒火龙币，火龙币可通过做任务兑换收益", "新人累计签到还有额外火龙币奖励",
                   "新人看剧5分钟后满0.3元就能提现",
                   "（原「吊打一众同类软件」「妥妥躺赚白嫖啊」「换成现金提走」2026-09-21 新规已删，待重写）"],
     "台词一字不改；2026-09-21 优矩新规：无广告类/躺赚白嫖/吊打竞品/直接提现 必须删改，收益只用 4 条固定话术"),
    ("硬切点10.050", ["10.050"], "硬切点不动"),
    ("直接锚定起身", ["直字", "接字", "4.350", "4.500", "5.000"], "说直接时重心前压、接字离座、5秒站直"),
    ("持续前走", ["前跨", "交替落脚"], "5.250第一跨、至少三次交替落脚、不停步"),
    ("手机全程举屏", ["不放手", "不换手", "举屏"], "0-10.050不放手、3.000-10.050举屏朝观众"),
    ("@图3原样保留", ["原样保留", "不重绘"], "@图3内容原样裁切入屏不重绘"),
    ("@图3透视圆角", ["透视形变", "圆角"], "@图3随手机姿态透视形变、圆角边框裁切"),
    ("屏外无UI", ["屏外不新增", "UI"], "屏外不新增UI或可读文字"),
    ("声音年龄", ["25岁"], "25岁左右中文男声"),
    ("声音音色", ["清亮沉稳"], "音色"),
    ("声音表达", ["像熟人分享"], "表达像熟人分享"),
    ("声音招呼笃定", ["招呼感", "笃定"], "开场带招呼感、后段自然笃定"),
    ("口型同步", ["口型"], "口型与中文人声自然同步"),
    ("镜头后退跟随", ["后退跟随", "横向换位", "后退量小于人物前行量"], "5.250后摄影机后退跟随横向换位"),
    ("空闲手克制", ["克制"], "空闲手只做克制分享手势"),
    ("负面-口型错位", ["口型错位"], "负面含口型错位"),
    ("负面-多余的话", ["多余的话", "乱语"], "负面含纯干扰项"),
    ("负面-白底入画", ["白底入画"], "负面含白底入画"),
    ("负面-换手翻面", ["换手翻面"], "负面含换手翻面"),
    ("彩铅还原写实", ["彩铅", "真人", "写实"], "从彩铅三视图还原真人照片级写实"),
    ("参考图@图1", ["男主_彩铅三视图_v3"], "@图1=男主彩铅三视图v3"),
    ("参考图@图2", ["场景_v2"], "@图2=场景"),
    ("参考图@图3", ["火龙漫剧_闪屏页_用户提供"], "@图3=闪屏页"),
    ("提交稿存在", ["@图1仅作男主参考"], "有可独立投喂提交稿"),
]

def main():
    path = sys.argv[1] if len(sys.argv) > 1 else ""
    if not path:
        print("用法: python3 verify_storyboard_checks.py <分镜文件路径>")
        return 2
    text = load(path)
    missing = []
    for name, keywords, note in CHECKS:
        for kw in keywords:
            if kw not in text:
                missing.append(f"  [{name}] 缺关键词「{kw}」（{note}）")
    if missing:
        print(f"BLOCKED: 分镜缺 {len(missing)} 条定案规则")
        print("\n".join(missing))
        return 1
    print(f"PASS: {len(CHECKS)} 条定案规则全部核验通过，文件 {path}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
